# Make scripts-font.css : the superscripts and subscripts of the code of the manual in one font.
#
# Fira-Mono, the font of the code in the Racket manuals, has the superscript and subscript digits and signs but not the
# subscript letters (U+2090-209C : ₐ ₑ ₒ ₓ ₕ ₖ ₗ ₘ ₙ ₚ ₛ ₜ) nor ⁰ and ⁱ : the browser takes them in another font and
# they are not at the level of the others (Bₖ₋₁). The superscripts and subscripts are taken from a subset of
# DejaVu Sans Mono , whose subscripts are lowered here by 0.19 em as those of Fira-Mono (in DejaVu Sans Mono they
# stand on the baseline).
#
# Usage : python3 scripts-font.py       (needs fontTools : pip install fonttools)
# Author: Damien Mattei

import base64
import io
import os

from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont

SOURCE = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FAMILY = "Scheme-PLUS-Scripts"
UNICODES = [0x00B2, 0x00B3, 0x00B9] + list(range(0x2070, 0x20A0))
SUBSCRIPTS = range(0x2080, 0x209D)
LOWER = 0.19  # em , the bottom of the subscripts of Fira-Mono (₁ : -0.193 em)
CSS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "scripts-font.css")


def make_font():
    font = TTFont(SOURCE)
    options = Options()
    options.flavor = "woff"
    subsetter = Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)
    dy = -round(LOWER * font["head"].unitsPerEm)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    lowered = {}
    for code in SUBSCRIPTS:
        name = cmap.get(code)
        if name and name not in lowered:
            # drawn decomposed : a component shared with a superscript is not moved with it
            pen = TTGlyphPen(glyph_set)
            glyph_set[name].draw(TransformPen(pen, (1, 0, 0, 1, 0, dy)))
            lowered[name] = pen.glyph()
    for name, glyph in lowered.items():
        font["glyf"][name] = glyph
    # a modified font : renamed
    for record in font["name"].names:
        if record.nameID in (1, 4, 16):
            record.string = FAMILY
        elif record.nameID == 6:
            record.string = FAMILY + "-Book"
    out = io.BytesIO()
    font.save(out)  # the bounding boxes are recomputed
    return out.getvalue(), dy


def write_css(woff, dy):
    with open(CSS, "w", encoding="utf-8") as f:
        f.write(f"""/* Superscripts and subscripts of the code in one font.

   Fira-Mono, the font of the code in the Racket manuals, has the superscript and subscript digits and signs
   (U+2074-208E : ⁴ ... ⁹ ⁿ ₀ ... ₉ ₊ ₋ ₍ ₎) but not the subscript letters (U+2090-209C : ₐ ₑ ₒ ₓ ₕ ₖ ₗ ₘ ₙ ₚ ₛ ₜ)
   nor ⁰ and ⁱ : the browser takes them in another font and they are not at the level of the others (Bₖ₋₁).
   All the superscripts and subscripts are taken here in the same font, a subset of DejaVu Sans Mono
   (U+00B2-00B3, U+00B9, U+2070-209F) whose subscripts (U+2080-209C) are lowered by {LOWER} em ({dy} units) as those
   of Fira-Mono, renamed {FAMILY} ; the rest of the code stays in Fira-Mono.

   DejaVu Sans Mono : https://dejavu-fonts.github.io/ , Bitstream Vera license (DejaVu changes are in public domain).

   Generated by scripts-font.py , included in the page by Scheme-PLUS-for-Racket.scrbl (css-addition of its content). */

@font-face {{
  font-family: '{FAMILY}';
  src: url(data:font/woff;base64,{base64.b64encode(woff).decode('ascii')}) format('woff');
  unicode-range: U+00B2-00B3, U+00B9, U+2070-209F;
}}

/* html : more specific than the rules of manual-racket.css , which come after this one in the page */
html .RktIn, html .RktRdr, html .RktPn, html .RktMeta, html .RktMod, html .RktKw, html .RktVar,
html .RktSym, html .RktRes, html .RktOut, html .RktCmt, html .RktVal, html .RktBlk, html .RktErr {{
  font-family: '{FAMILY}', 'Fira-Mono', monospace;
}}
""")


if __name__ == "__main__":
    woff, dy = make_font()
    write_css(woff, dy)
    print(f"{CSS} : font of {len(woff)} bytes , subscripts lowered by {dy} units")
